//! Rust SDK for writing Marqdo native plugins against plugin ABI v1.
//!
//! The SDK is the plugin-developer side of `include/marqdo_plugin_abi_v1.h`.
//! It hides the raw C layout behind safe wrappers and provides the
//! [`mq_plugin_entry!`] macro that exports the required
//! `mq_plugin_entry_v1` symbol:
//!
//! ```
//! use marqdo_plugin_sdk::{mq_plugin_entry, CallContext, PluginError, Value};
//!
//! fn add(_ctx: &mut CallContext, args: &[u8]) -> Result<Vec<u8>, PluginError> {
//!     let request = marqdo_plugin_sdk::wire::decode_request(args)?;
//!     let values = request.typed_args()?;
//!     let a = marqdo_plugin_sdk::wire::int_arg(&values, "a")?;
//!     let b = marqdo_plugin_sdk::wire::int_arg(&values, "b")?;
//!     marqdo_plugin_sdk::wire::success(Some(Value::Int((a + b).into())))
//! }
//!
//! mq_plugin_entry! {
//!     name: "demo.solver",
//!     version: "0.1.0",
//!     exports: {
//!         "solver.add" => "($a: Int, $b: Int) -> Int" => add,
//!     }
//! }
//! ```
//!
//! The SDK never depends on host-only crates: it only uses the shared ABI
//! types and the JSON wire envelope from `marqdo-plugin-abi`. Building a
//! plugin does not grant it any capability; authorization is a separate host
//! decision performed before loading.

#![deny(missing_docs)]

